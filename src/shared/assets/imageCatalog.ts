export function getDefaultRoomImage(room: {
  category: string;
  number: string;
}) {
  const number = room.number || "";
  const isSingle = room.category === "Single" || number.startsWith("SR");
  const isDouble = room.category === "Double" || number.startsWith("DR");

  if (isSingle) {
    const idx =
      parseInt(number.replace(/\D/g, "") || "0") %
      IMAGE_CATALOG.rooms.singleGallery.length;
    return IMAGE_CATALOG.rooms.singleGallery[idx];
  }
  if (isDouble) {
    const idx =
      parseInt(number.replace(/\D/g, "") || "0") %
      IMAGE_CATALOG.rooms.doubleGallery.length;
    return IMAGE_CATALOG.rooms.doubleGallery[idx];
  }
  if (
    room.category === "VIP" ||
    room.category === "Suite" ||
    number.startsWith("VR")
  )
    return IMAGE_CATALOG.rooms.vip;

  return IMAGE_CATALOG.rooms.single;
}

export function getDefaultMenuImage(item: {
  name: string;
  type: string;
  category: string;
  imageUrl?: string;
}) {
  const normalizedName = item.name.trim().toLowerCase();

  if (normalizedName === "t-bone steak") return IMAGE_CATALOG.menu.steak;
  if (normalizedName === "grilled hake") return IMAGE_CATALOG.menu.fish;
  if (normalizedName === "greek salad") return IMAGE_CATALOG.menu.salad;
  if (normalizedName === "windhock lager") return IMAGE_CATALOG.menu.beer;
  if (normalizedName === "red wine glass") return IMAGE_CATALOG.menu.wine;

  if (
    item.imageUrl &&
    item.imageUrl.startsWith("/assets/images/") &&
    !item.imageUrl.endsWith(".svg")
  ) {
    return item.imageUrl;
  }

  if (item.type === "Bar" || item.category === "Drinks") {
    return IMAGE_CATALOG.showcase.bar[0];
  }

  return IMAGE_CATALOG.showcase.restaurant[0];
}

export function getMenuImage(item: {
  name: string;
  type: string;
  category: string;
  imageUrl?: string;
}) {
  if (
    item.imageUrl &&
    !item.imageUrl.includes("pexels.com") &&
    !item.imageUrl.includes("picsum.photos") &&
    !item.imageUrl.endsWith(".svg")
  ) {
    return item.imageUrl;
  }

  return getDefaultMenuImage(item);
}
